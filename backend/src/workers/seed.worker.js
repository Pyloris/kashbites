import { Worker } from 'bullmq';
import { redisConnection } from '../config/redis.js';
import { SEED_QUEUE_NAME } from '../queues/seed.queue.js';
import { connectDb } from '../database/connect.js';
import { Product } from '../database/models/products.model.js';
import { Category } from '../database/models/categories.model.js';
import { Review } from '../database/models/reviews.model.js';
import { Admin } from '../database/models/admins.model.js';
import { User } from '../database/models/users.model.js';
import { Coupon } from '../database/models/coupons.model.js';
import { Order } from '../database/models/orders.model.js';
import { ShippingConfig } from '../database/models/shipping-configs.model.js';
import {
    productsStore,
    categoriesStore,
    adminsStore,
    usersStore,
    couponsStore,
    ordersStore,
    shippingConfigStore,
} from '../data/store.js';
import { initialReviews } from '../data/seedData.js';

let seedWorker = null;

/**
 * Execute seeding logic into MongoDB ensuring no explicit _id is passed.
 * All document _ids will be naturally generated by MongoDB as ObjectIds.
 */
export const executeSeed = async () => {
    await connectDb();

    const existingCount = await Product.countDocuments();
    if (existingCount > 0) {
        console.log(`[Worker:Seed] Database is already seeded (${existingCount} products present). Skipping seed.`);
        return { skipped: true, existingCount };
    }

    console.log('[Worker:Seed] Database is not seeded. Seeding data into MongoDB (auto-generating _id)...');

    // 1. Categories
    await Category.deleteMany({});
    const cleanCategories = categoriesStore.map(({ _id, ...rest }) => rest);
    await Category.insertMany(cleanCategories);

    // 2. Products (strip _id if any, let MongoDB generate ObjectId)
    await Product.deleteMany({});
    const cleanProducts = productsStore.map(({ _id, ...rest }) => rest);
    const insertedProducts = await Product.insertMany(cleanProducts);

    // Build slug -> MongoDB ObjectId map
    const slugToIdMap = {};
    for (const prod of insertedProducts) {
        slugToIdMap[prod.slug] = prod._id.toString();
    }

    // 3. Reviews (strip _id and link to generated product._id via slug)
    await Review.deleteMany({});
    const cleanReviews = initialReviews.map(({ _id, ...review }) => {
        let productId = review.productId;
        if (review.productSlug && slugToIdMap[review.productSlug]) {
            productId = slugToIdMap[review.productSlug];
        } else if (review.productId && slugToIdMap[review.productId]) {
            productId = slugToIdMap[review.productId];
        } else {
            // Map legacy review keys to actual seeded product ObjectIds
            const legacyMap = {
                'kb-prod-01': slugToIdMap['kashmiri-walnuts'],
                'kb-prod-02': slugToIdMap['kashmiri-almonds'],
                'kb-prod-03': slugToIdMap['dried-apricots'],
                'kb-prod-04': slugToIdMap['walnut-kernels'],
                'kb-prod-05': slugToIdMap['signature-collection-emerald-box'],
                'kb-prod-06': slugToIdMap['mixed-dry-fruits'],
                'kb-prod-07': slugToIdMap['valley-trio-harvest-combo'],
                'kb-prod-08': slugToIdMap['kashmiri-raisins'],
            };
            productId = legacyMap[review.productId] || insertedProducts[0]._id.toString();
        }
        return {
            ...review,
            productId,
        };
    });
    await Review.insertMany(cleanReviews);

    // 4. Admins
    await Admin.deleteMany({});
    const cleanAdmins = adminsStore.map(({ _id, ...rest }) => rest);
    await Admin.insertMany(cleanAdmins);

    // 5. Users
    await User.deleteMany({});
    const cleanUsers = usersStore.map(({ _id, ...rest }) => rest);
    await User.insertMany(cleanUsers);

    // 6. Coupons
    await Coupon.deleteMany({});
    const cleanCoupons = couponsStore.map(({ _id, ...rest }) => rest);
    await Coupon.insertMany(cleanCoupons);

    // 7. Shipping Config
    await ShippingConfig.deleteMany({});
    const { _id: _, ...cleanShippingConfig } = shippingConfigStore;
    await ShippingConfig.create(cleanShippingConfig);

    // 8. Orders (map item productId to generated product._id)
    await Order.deleteMany({});
    const cleanOrders = ordersStore.map(({ _id, items, ...orderRest }) => {
        const cleanItems = (items || []).map(({ _id: item_id, productId, slug, ...itemRest }) => {
            const mappedId = (slug && slugToIdMap[slug]) ||
                (productId && slugToIdMap[productId]) ||
                insertedProducts[0]._id.toString();
            return {
                ...itemRest,
                slug,
                productId: mappedId,
            };
        });
        return {
            ...orderRest,
            items: cleanItems,
        };
    });
    await Order.insertMany(cleanOrders);

    console.log(`[Worker:Seed] Seeding completed: ${insertedProducts.length} products, ${cleanReviews.length} reviews, ${cleanCategories.length} categories, ${cleanAdmins.length} admin, ${cleanUsers.length} users, ${cleanCoupons.length} coupons, and ${cleanOrders.length} orders.`);

    return {
        success: true,
        seeded: {
            products: insertedProducts.length,
            reviews: cleanReviews.length,
            categories: cleanCategories.length,
            admins: cleanAdmins.length,
            users: cleanUsers.length,
            coupons: cleanCoupons.length,
            orders: cleanOrders.length,
        },
    };
};

/**
 * Initializes and starts the BullMQ seed worker.
 */
export const startSeedWorker = async () => {
    if (seedWorker) {
        return seedWorker;
    }

    console.log(`[Worker:Seed] Initializing BullMQ seed worker on queue '${SEED_QUEUE_NAME}'...`);

    seedWorker = new Worker(
        SEED_QUEUE_NAME,
        async (job) => {
            console.log(`[Worker:Seed] Processing seed job ${job.id} (${job.name})...`);
            const result = await executeSeed();
            return result;
        },
        {
            connection: redisConnection,
            concurrency: 1,
        }
    );

    seedWorker.on('completed', (job, returnvalue) => {
        console.log(`[Worker:Seed] Job ${job.id} finished successfully:`, returnvalue);
    });

    seedWorker.on('failed', (job, err) => {
        console.error(`[Worker:Seed] Job ${job?.id} failed:`, err?.message || err);
    });

    console.log(`[Worker:Seed] BullMQ seed worker active and listening for seed jobs.`);
    return seedWorker;
};

export default startSeedWorker;
